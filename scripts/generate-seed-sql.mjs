// Generates db/seed.sql from functions/_lib/seed-data.js so D1 starts with the same content.
// Usage: npm run db:seed:generate
import { writeFileSync } from 'node:fs';
import { MOSQUES, CONTACTS, EVENTS, HIGHLIGHTS, FEEDBACK } from '../functions/_lib/seed-data.js';

const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, rows) =>
  rows.length
    ? `INSERT INTO ${table} (${Object.keys(rows[0]).join(', ')}) VALUES\n` +
      rows.map((r) => `  (${Object.values(r).map(q).join(', ')})`).join(',\n') + ';\n'
    : '';

const sql = [
  '-- GENERATED by scripts/generate-seed-sql.mjs – do not edit by hand.',
  'DELETE FROM feedback; DELETE FROM highlights; DELETE FROM events; DELETE FROM contacts; DELETE FROM mosques;',
  insert('mosques', MOSQUES.map((m) => ({
    id: m.id, slug: m.slug, name: m.name, subtitle: m.subtitle, type: m.type, street: m.street, zip: m.zip,
    city: m.city, district: m.district, lat: m.lat, lng: m.lng, opened_year: m.openedYear, image: m.image,
    image_alt: m.imageAlt, short_description: m.shortDescription, description: m.description,
    features: JSON.stringify(m.features), email: m.email, booking_email: m.bookingEmail, phone: m.phone, sort_order: m.sortOrder
  }))),
  insert('contacts', CONTACTS.map((c) => ({
    id: c.id, mosque_id: c.mosqueId, name: c.name, role: c.role, email: c.email, phone: c.phone, photo: c.photo, sort_order: c.sortOrder
  }))),
  insert('events', EVENTS.map((e) => ({
    id: e.id, mosque_id: e.mosqueId, title: e.title, description: e.description,
    starts_at: new Date(e.startsAt).toISOString(), ends_at: e.endsAt ? new Date(e.endsAt).toISOString() : null,
    location: e.location, image: e.image
  }))),
  insert('highlights', HIGHLIGHTS.map((h) => ({
    id: h.id, mosque_id: h.mosqueId, title: h.title, summary: h.summary, date: h.date, image: h.image, link: h.link
  }))),
  insert('feedback', FEEDBACK.map((f) => ({
    id: f.id, mosque_id: f.mosqueId, name: f.name, visit_type: f.visitType, rating: f.rating, text: f.text,
    visited_on: f.visitedOn, status: f.status, created_at: f.createdAt
  })))
].join('\n');

writeFileSync(new URL('../db/seed.sql', import.meta.url), sql);
console.log('db/seed.sql written');
